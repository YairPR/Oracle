-- Tabla de clientes (Tiene FK física que la une a tbl_personas)
CREATE TABLE AST_DUMMY_APP.tbl_clientes (
    cliente_id   NUMBER        GENERATED BY DEFAULT AS IDENTITY,
    dni_ref      VARCHAR2(20)  NOT NULL,
    tipo_cliente VARCHAR2(50)  DEFAULT 'ESTÁNDAR',
    CONSTRAINT pk_tbl_clientes PRIMARY KEY (cliente_id),
    CONSTRAINT fk_cli_persona FOREIGN KEY (dni_ref) REFERENCES AST_DUMMY_APP.tbl_personas(dni)
) TABLESPACE USERS;

-- Tabla de empleados (Tiene FK física que la une a tbl_personas)
CREATE TABLE AST_DUMMY_APP.tbl_empleados (
    empleado_id  NUMBER        GENERATED BY DEFAULT AS IDENTITY,
    dni_emp      VARCHAR2(20)  NOT NULL,
    cargo        VARCHAR2(100) NOT NULL,
    salario      NUMBER(10,2),
    CONSTRAINT pk_tbl_empleados PRIMARY KEY (empleado_id),
    CONSTRAINT fk_emp_persona FOREIGN KEY (dni_emp) REFERENCES AST_DUMMY_APP.tbl_personas(dni)
