-- Tabla principal de personas (contiene datos personales sensibles)
CREATE TABLE AST_DUMMY_APP.tbl_personas (
    dni             VARCHAR2(20)  NOT NULL,
    nombre          VARCHAR2(100) NOT NULL,
    apellidos       VARCHAR2(150) NOT NULL,
    telefono        VARCHAR2(20),
    email           VARCHAR2(150),
    iban            VARCHAR2(30),   -- Columna Bancaria IBAN (Debe ser detectada automáticamente)
    cuenta_ccc      VARCHAR2(30),   -- Columna Bancaria CCC (Debe ser detectada automáticamente)
    nie_cif         VARCHAR2(20),   -- Documentos de identidad especiales (NIE/CIF)
    cod_dni_falso   VARCHAR2(20),   -- ENGAÑO: Se llama DNI pero tiene números secuenciales (no cumple patrón)
    correo_interno  VARCHAR2(50),   -- ENGAÑO: Se llama correo pero tiene textos "usuario_X" (no cumple patrón)
    CONSTRAINT pk_tbl_personas PRIMARY KEY (dni)
